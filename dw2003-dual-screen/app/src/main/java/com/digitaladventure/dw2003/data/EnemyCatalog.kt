    private val byId by lazy { ENTRIES.associateBy { it.enemyId } }
    private val byDigimonId by lazy { ENTRIES.associateBy { it.digimonId } }

    fun template(enemyId: Int): Template? = byId[enemyId]

    fun templateByDigimonId(digimonId: Int): Template? = byDigimonId[digimonId]

    fun techniqueName(skillId: Int, spanish: Boolean): String? {
        if (skillId <= 0) return null
        val names = if (spanish) SKILL_ES else SKILL_EN
        names.getOrNull(skillId)?.takeIf { it.isNotBlank() && it != "a" }?.let { return it }
        return if (spanish) ENEMY_TECH_ES[skillId] else ENEMY_TECH_EN[skillId]
    }

    fun techniqueLabel(skillId: Int, spanish: Boolean): String {
        val name = techniqueName(skillId, spanish) ?: if (spanish) "Técnica $skillId" else "Tech $skillId"
        val power = SKILL_POWER[skillId] ?: TechniquePower.powerOf(name)
        return if (power != null && power > 0) "$name ($power)" else name
    }

