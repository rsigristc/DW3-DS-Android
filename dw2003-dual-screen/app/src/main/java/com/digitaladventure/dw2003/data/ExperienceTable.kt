    fun cumulativeForLevel(profileId: Int, level: Int): Long {
        val profile = thresholds.getOrNull(profileId) ?: return 0L
        return profile[(level.coerceIn(1, MAX_LEVEL) - 1)].toLong()
    }

    fun nextLevel(profileId: Int, level: Int): Long? =
        if (level >= MAX_LEVEL) null else cumulativeForLevel(profileId, level + 1)

    fun progress(profileId: Int, level: Int, experience: Long): Float {
        if (level >= MAX_LEVEL) return 1f
        val current = cumulativeForLevel(profileId, level)
        val next = nextLevel(profileId, level) ?: return 1f
        val span = next - current
        return if (span <= 0L) 0f else ((experience - current).toFloat() / span).coerceIn(0f, 1f)
    }
