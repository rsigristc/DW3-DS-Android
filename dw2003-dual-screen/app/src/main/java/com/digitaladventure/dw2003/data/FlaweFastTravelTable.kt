    fun fieldIcon(mapId: Int): Int? {
        if (mapId !in 0x0200..0x02D6) return null
        val encoded = stageIconCodes[mapId and 0xFF]
        val icons = if (mapId >= 0x0270) amaterasuIcons else asukaIcons
        return icons.firstOrNull { it.iconCode == (encoded and 0x7F) + 1 }?.mapId
    }

    private val codeByMapId: Map<Int, Int> = asukaIcons.associate { it.mapId to it.iconCode }
    val asukaMapIds: Set<Int> = codeByMapId.keys

    fun iconCode(mapId: Int): Int? = codeByMapId[mapId]
        ?: amaterasuIcons.firstOrNull { it.mapId == mapId }?.iconCode
